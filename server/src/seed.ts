import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { CATEGORY_IDS, DIFFICULTIES, type CategoryId, type Difficulty } from '../../shared/rules';

export interface RawQuestion {
  c: string;
  d: string;
  q: string;
  a: string;
  w: string[];
  e: string;
  t: string | null;
  asOf?: string;
  /** attribution for questions that are not original, e.g. "Open Trivia DB (CC BY-SA 4.0)" */
  src?: string;
}

export interface SeedQuestion {
  category: CategoryId;
  difficulty: Difficulty;
  question: string;
  options: string[];
  correctIndex: number;
  explanation: string;
  tradition: string | null;
  validAsOf: string | null;
  source: string | null;
}

export interface SeedIssue {
  file: string;
  question: string;
  error: string;
}

export interface SeedLoadResult {
  files: string[];
  questions: SeedQuestion[];
  issues: SeedIssue[];
}

const here = path.dirname(fileURLToPath(import.meta.url));
export const SEED_ROOT = path.resolve(here, '../../seed');
/** hand-written, generated by `questions:generate`, imported by `questions:import` */
export const SEED_DIRS = ['questions', 'generated', 'imported'] as const;

/** Deterministic string hash (FNV-1a) so seeded answer positions are stable across installs. */
function hash(s: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}

/** Text used for duplicate detection: case, accents, punctuation and spacing are ignored. */
export function normalizeQuestionText(s: string): string {
  return s
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^\p{L}\p{N}]+/gu, ' ')
    .trim();
}

const isText = (v: unknown): v is string => typeof v === 'string' && v.trim().length > 0;

export function validateRawQuestion(r: RawQuestion): string | null {
  if (!r || typeof r !== 'object') return 'not an object';
  if (!CATEGORY_IDS.includes(r.c as CategoryId)) return `unknown category ${r.c}`;
  if (!DIFFICULTIES.includes(r.d as Difficulty)) return `unknown difficulty ${r.d}`;
  if (!isText(r.q) || r.q.length < 10) return 'question too short';
  if (!isText(r.a)) return 'answer required';
  if (!Array.isArray(r.w) || r.w.length !== 3) return 'needs exactly 3 wrong options';
  if (!r.w.every(isText)) return 'wrong options must be non-empty text';
  const all = [r.a, ...r.w].map((o) => o.trim().toLowerCase());
  if (new Set(all).size !== 4) return 'options must be distinct';
  if (!isText(r.e)) return 'explanation required';
  if (r.t !== null && r.t !== undefined && typeof r.t !== 'string') return 'tradition must be text or null';
  if (r.asOf !== undefined && !/^\d{4}-\d{2}-\d{2}$/.test(r.asOf)) return 'asOf must be YYYY-MM-DD';
  if (r.c === 'politics' && !r.asOf) return 'current-affairs questions need asOf date';
  if (r.src !== undefined && !isText(r.src)) return 'src must be non-empty text';
  return null;
}

export function toSeedQuestion(r: RawQuestion): SeedQuestion {
  const err = validateRawQuestion(r);
  if (err) throw new Error(`Invalid seed question "${r?.q}": ${err}`);
  const correctIndex = hash(r.q) % 4;
  const options = [...r.w];
  options.splice(correctIndex, 0, r.a);
  return {
    category: r.c as CategoryId,
    difficulty: r.d as Difficulty,
    question: r.q,
    options,
    correctIndex,
    explanation: r.e,
    tradition: r.t ?? null,
    validAsOf: r.asOf ?? null,
    source: r.src ?? null,
  };
}

/** Every seed file, in a stable order. */
export function listSeedFiles(root = SEED_ROOT): string[] {
  const files: string[] = [];
  for (const dir of SEED_DIRS) {
    const full = path.join(root, dir);
    if (!existsSync(full)) continue;
    for (const name of readdirSync(full).filter((n) => n.endsWith('.json')).sort()) files.push(path.join(full, name));
  }
  return files;
}

export function readRawFile(file: string): RawQuestion[] {
  const data = JSON.parse(readFileSync(file, 'utf8')) as unknown;
  if (!Array.isArray(data)) throw new Error('file must contain a JSON array');
  return data as RawQuestion[];
}

/** Loads and validates every seed file, collecting problems instead of stopping at the first. */
export function collectSeedQuestions(root = SEED_ROOT): SeedLoadResult {
  const files = listSeedFiles(root);
  const questions: SeedQuestion[] = [];
  const issues: SeedIssue[] = [];
  const seen = new Map<string, string>();
  for (const file of files) {
    const rel = path.relative(root, file).replace(/\\/g, '/');
    let raw: RawQuestion[];
    try {
      raw = readRawFile(file);
    } catch (e) {
      issues.push({ file: rel, question: '', error: (e as Error).message });
      continue;
    }
    for (const r of raw) {
      const err = validateRawQuestion(r);
      if (err) {
        issues.push({ file: rel, question: String(r?.q ?? ''), error: err });
        continue;
      }
      const key = normalizeQuestionText(r.q);
      const first = seen.get(key);
      if (first) {
        issues.push({ file: rel, question: r.q, error: `duplicate of a question in ${first}` });
        continue;
      }
      seen.set(key, rel);
      questions.push(toSeedQuestion(r));
    }
  }
  return { files, questions, issues };
}

export function formatIssues(issues: SeedIssue[], limit = 20): string {
  const lines = issues.slice(0, limit).map((i) => `  ${i.file}: ${i.error}${i.question ? ` - "${i.question}"` : ''}`);
  if (issues.length > limit) lines.push(`  ...and ${issues.length - limit} more`);
  return lines.join('\n');
}

/** Throws if any seed file has a problem, so a broken bank never reaches the database. */
export function loadSeedQuestions(root = SEED_ROOT): SeedQuestion[] {
  const { questions, issues } = collectSeedQuestions(root);
  if (issues.length) throw new Error(`Seed question bank has ${issues.length} problem(s):\n${formatIssues(issues)}`);
  return questions;
}

/** Bump when the way seed files map to database rows changes, so existing databases reseed. */
const SEED_FORMAT_VERSION = '2';

/** Changes whenever any seed file is added, removed or edited. */
export function seedFingerprint(root = SEED_ROOT): string {
  const h = createHash('sha256');
  h.update(SEED_FORMAT_VERSION);
  for (const file of listSeedFiles(root)) {
    h.update(path.relative(root, file).replace(/\\/g, '/'));
    h.update('\0');
    h.update(readFileSync(file));
    h.update('\0');
  }
  return h.digest('hex');
}
