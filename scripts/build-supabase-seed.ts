/** Generates supabase/seed.sql from the seed folder (same data the local server loads). */
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadSeedQuestions } from '../server/src/seed';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'supabase', 'seed.sql');
const lit = (v: string | null) => (v === null ? 'null' : `'${v.replace(/'/g, "''")}'`);

const rows = loadSeedQuestions().map(
  (q) =>
    `  (${lit(q.category)}, ${lit(q.difficulty)}, ${lit(q.question)}, ${lit(JSON.stringify(q.options))}::jsonb, ${q.correctIndex}, ${lit(
      q.explanation,
    )}, ${lit(q.tradition)}, ${q.validAsOf ? `${lit(q.validAsOf)}::date` : 'null'}, ${lit(q.source)})`,
);

const sql = `-- GENERATED by \`npm run seed:supabase\` from seed/questions, seed/generated and seed/imported - do not edit by hand.
insert into public.questions (category, difficulty, question, options, correct_index, explanation, tradition, valid_as_of, source) values
${rows.join(',\n')}
on conflict (question) do update set
  options = excluded.options, correct_index = excluded.correct_index, explanation = excluded.explanation,
  difficulty = excluded.difficulty, category = excluded.category, tradition = excluded.tradition,
  valid_as_of = excluded.valid_as_of, source = excluded.source;
`;
writeFileSync(out, sql);
console.log(`wrote ${rows.length} questions to ${path.relative(root, out)}`);
